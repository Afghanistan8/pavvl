#!/usr/bin/env node
/**
 * Advisory adversarial review for a Pavvl steward.
 *
 * This is a convenience, not a substitute for the test suite. It re-derives, from
 * the repository source, a handful of the guarantees Pavvl claims, so a reviewer
 * can spot drift quickly:
 *
 *   1. the contract carries the exact pinned Studionet header;
 *   2. every @gl.public.write calls _guard_chain() before it does anything;
 *   3. every write has a gate in get_actions, and every gate has a write, so no
 *      callable path is missing from what the contract publishes for clients;
 *   4. there is no pause / upgrade / owner / admin / operator surface;
 *   5. the contract refuses every chain but Studionet (61999);
 *   6. no node judges another node's observations of the evidence: a node that
 *      cannot receive images refuses, and every voting validator examines it;
 *   7. committed text carries no model or assistant attribution.
 *
 * Hard failures exit non-zero. Advisories are printed and do not fail the run.
 *
 * Usage
 *   node tools/adversarial_review.mjs
 */

import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACT = join(ROOT, "contracts", "pavvl.py");

const EXPECTED_HEADER = [
  "# v0.2.16",
  '# { "Depends": "py-genlayer:132536jbnxkd1axfxg5rpfr5b60cr11adm2y4r90hgn0l59qsp9w" }',
];

const SKIP_DIRS = new Set([
  ".git", "node_modules", ".next", "dist", "artifacts", "__pycache__",
  ".pytest_cache", "coverage", "proofs",
]);
const TEXT_EXT = new Set([
  ".py", ".md", ".mjs", ".js", ".json", ".toml", ".ini", ".txt", ".yml", ".yaml",
]);
const ATTRIBUTION = /(claude|anthropic|opencode|open-code|cursor|copilot|chatgpt|co-authored-by|generated by|as an ai|language model)/i;

/**
 * Which get_actions gate each write obeys. `open_case` is the one ungated write:
 * it creates the stream of cases a wallet is allowed to start. Every other write
 * must have a gate whose `ok` the contract also enforces itself.
 */
const WRITE_TO_GATE = {
  open_case: null,
  revise_terms: "revise",
  accept_case: "accept",
  decline_case: "decline",
  withdraw_case: "withdraw_case",
  accept_inspector: "accept_inspector",
  fund_case: "fund",
  expire_case: "expire",
  submit_image: "file",
  submit_text: "file",
  mark_ready: "ready",
  lapse_case: "lapse",
  request_assessment: "assess",
  challenge: "challenge",
  readjudicate: "readjudicate",
  close_challenge: "close_challenge",
  finalize: "finalize",
  withdraw: "withdraw",
};

const failures = [];
const advisories = [];
const passes = [];

function fail(message) {
  failures.push(message);
}
function advise(message) {
  advisories.push(message);
}
function pass(message) {
  passes.push(message);
}

function read(path) {
  return readFileSync(path, "utf8");
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const info = statSync(full);
    if (info.isDirectory()) {
      if (SKIP_DIRS.has(entry)) continue;
      walk(full, out);
    } else {
      out.push(full);
    }
  }
  return out;
}

/** Every @gl.public.write method name, in source order. */
function writeNames(source) {
  const lines = source.split("\n");
  const names = [];
  for (let i = 0; i < lines.length; i += 1) {
    if (!/^    @gl\.public\.write(?:\.payable)?\s*$/.test(lines[i])) continue;
    for (let j = i + 1; j < Math.min(i + 6, lines.length); j += 1) {
      const m = /^    def (\w+)\(/.exec(lines[j]);
      if (m) {
        names.push(m[1]);
        break;
      }
    }
  }
  return names;
}

/** 1. Pinned header. */
function checkHeader(source) {
  const lines = source.split("\n");
  if (lines[0] !== EXPECTED_HEADER[0] || lines[1] !== EXPECTED_HEADER[1]) {
    fail(`contract header is not the pinned Studionet header\n  expected:\n${EXPECTED_HEADER.join("\n")}`);
  } else {
    pass("pinned Studionet header (v0.2.16 + proven runner)");
  }
  if (/(^|\n)# .*:(test|latest)\b/.test(source.slice(0, 300))) {
    fail("runner alias :test/:latest present in the header (rejected in non-debug mode)");
  }
}

/** 2. Every write guards the chain first. */
function checkWritesGuardChain(source) {
  const lines = source.split("\n");
  const writes = [];
  for (let i = 0; i < lines.length; i += 1) {
    if (/^    @gl\.public\.write(?:\.payable)?\s*$/.test(lines[i])) {
      let j = i + 1;
      while (j < lines.length && !/^    def /.test(lines[j])) j += 1;
      if (j >= lines.length) continue;
      const name = /^    def (\w+)\(/.exec(lines[j])?.[1] ?? "(unknown)";
      let k = j + 1;
      while (k < lines.length && !/^    (def |@)/.test(lines[k])) k += 1;
      const body = lines.slice(j + 1, k);
      const guardAt = body.findIndex((l) => /^\s+_guard_chain\(\)/.test(l));
      writes.push({ name, guardAt, line: j + 1 });
    }
  }
  if (writes.length === 0) fail("no @gl.public.write methods found");
  const unguarded = writes.filter((w) => w.guardAt === -1);
  if (unguarded.length) {
    fail(`writes without _guard_chain(): ${unguarded.map((w) => w.name).join(", ")}`);
  } else {
    pass(`every write guards the chain (${writes.length} writes)`);
  }
  const late = writes.filter((w) => w.guardAt > 1);
  if (late.length) {
    advise(
      `_guard_chain() is not the first statement in: ` +
        late.map((w) => `${w.name} (line ${w.line}, offset ${w.guardAt})`).join(", "),
    );
  }
}

/**
 * 3. Write/gate coverage, contract only. Every write obeys a gate published by
 * get_actions (open_case excepted), and every published gate belongs to a write.
 * A write with no gate would be a hidden path; a gate with no write would be a
 * button the contract cannot honour.
 */
function checkWriteGateCoverage(source) {
  const names = writeNames(source);
  if (names.length === 0) {
    fail("no @gl.public.write methods found");
    return;
  }
  const unmapped = names.filter((n) => !(n in WRITE_TO_GATE));
  const missing = Object.keys(WRITE_TO_GATE).filter((n) => !names.includes(n));
  if (unmapped.length || missing.length) {
    fail(
      `the write set drifted from the review map\n  unmapped writes: ${unmapped.join(", ") || "-"}\n` +
        `  mapped but absent: ${missing.join(", ") || "-"}`,
    );
    return;
  }

  const returnMatch = /return \{"role": role,.*?\}/s.exec(source);
  if (!returnMatch) {
    fail("could not find the _acts_for return dict");
    return;
  }
  const contractKeys = new Set([...returnMatch[0].matchAll(/"(\w+)"\s*:/g)].map((m) => m[1]));

  const expectedGates = new Set(Object.values(WRITE_TO_GATE).filter(Boolean));
  expectedGates.add("role");
  const onlyContract = [...contractKeys].filter((k) => !expectedGates.has(k));
  const onlyMap = [...expectedGates].filter((k) => !contractKeys.has(k));
  if (onlyContract.length || onlyMap.length) {
    fail(
      `get_actions gates drifted from the write map\n  gates with no write: ${onlyContract.join(", ") || "-"}\n` +
        `  writes with no gate: ${onlyMap.join(", ") || "-"}`,
    );
  } else {
    pass(
      `every write has a gate and every gate has a write ` +
        `(${names.length} writes, ${contractKeys.size - 1} gates)`,
    );
  }

  const ungated = names.filter((n) => WRITE_TO_GATE[n] === null);
  if (ungated.length !== 1 || ungated[0] !== "open_case") {
    advise(`ungated writes are not just open_case: ${ungated.join(", ") || "-"}`);
  }
}

/** 4. No governance surface. */
function checkNoGovernanceSurface(source) {
  const forbiddenDefs = /^\s*def\s+(pause|unpause|upgrade|set_owner|transfer_ownership|grant_role|revoke_role|set_admin|set_operator|destroy|selfdestruct|delegate)\b/im;
  const found = forbiddenDefs.exec(source);
  if (found) {
    fail(`forbidden governance method found: ${found[1]}`);
  } else {
    pass("no pause/upgrade/owner/admin/operator method");
  }

  const stored = [...source.matchAll(/^\s*self\.(owner|admin|operator|upgrader|pauser)\s*[:=]/gim)].map(
    (m) => m[1],
  );
  if (stored.length) {
    fail(`a stored governance key is declared: ${stored.join(", ")}`);
  } else {
    pass("no stored owner/admin/operator/upgrade key");
  }

  if (/def\s+get_governance\b/.test(source)) {
    pass("get_governance view is present (auditable on chain)");
  } else {
    advise("no get_governance view; 'no governance' is not readable on chain");
  }
}

/** 5. The contract refuses every chain but Studionet. */
function checkStudionetOnly(source) {
  if (!/STUDIONET_CHAIN_ID\s*=\s*61999\b/.test(source)) {
    fail("STUDIONET_CHAIN_ID is not pinned to 61999");
  } else {
    pass("chain id pinned to Studionet (61999)");
  }
  const guard = /def _guard_chain\([^)]*\):(.*?)(?=\n    def |\n    @)/s.exec(source);
  if (!guard) {
    fail("could not find _guard_chain");
    return;
  }
  if (!/_refuse\(/.test(guard[1]) || !/STUDIONET_CHAIN_ID/.test(guard[1])) {
    fail("_guard_chain does not refuse a non-Studionet chain");
  } else {
    pass("_guard_chain refuses any chain but Studionet");
  }
}

/** 6. No node judges another node's observations of the evidence. */
function checkIndependentExamination(source) {
  const assessment = /def _assess\([^)]*\)[^:\n]*:(.*?)(?=\n    def |\n    @)/s.exec(source);
  if (!assessment) {
    fail("could not find _assess");
    return;
  }
  const body = assessment[1];
  if (/def _borrow\b/.test(source) || /\bborrowed\b/.test(source)) {
    fail("an observation-borrowing path exists (_borrow / borrowed)");
  } else {
    pass("no node judges another node's observations of the evidence");
  }
  if (
    !/if not sighted:/.test(body) ||
    !/cannot receive images/.test(body) ||
    !/raise gl\.vm\.UserError/.test(body)
  ) {
    fail("_assess does not refuse when the node's model cannot receive images");
  } else {
    pass("_assess refuses when the model cannot receive images (leader errors, validator dissents)");
  }
}

/** 7. No model/assistant attribution in committed text. */
function checkAttribution(files) {
  const self = fileURLToPath(import.meta.url);
  const hits = [];
  for (const file of files) {
    if (resolve(file) === resolve(self)) continue; // this script names the patterns
    const ext = file.slice(file.lastIndexOf("."));
    if (!TEXT_EXT.has(ext)) continue;
    // The probe/ tree is a captured third-party reference, not authored text.
    if (relative(ROOT, file).startsWith(`probe${"\\"}`) || relative(ROOT, file).startsWith("probe/")) {
      continue;
    }
    let text;
    try {
      text = readFileSync(file, "utf8");
    } catch {
      continue;
    }
    const lines = text.split("\n");
    lines.forEach((line, i) => {
      if (ATTRIBUTION.test(line)) hits.push(`${relative(ROOT, file)}:${i + 1}: ${line.trim()}`);
    });
  }
  if (hits.length) {
    advise(`possible attribution found (${hits.length}):\n  ${hits.join("\n  ")}`);
  } else {
    pass("no model/assistant attribution in authored text");
  }
}

function main() {
  let contractSource;
  try {
    contractSource = read(CONTRACT);
  } catch {
    fail(`cannot read ${CONTRACT}`);
    report();
    return;
  }

  checkHeader(contractSource);
  checkWritesGuardChain(contractSource);
  checkWriteGateCoverage(contractSource);
  checkNoGovernanceSurface(contractSource);
  checkStudionetOnly(contractSource);
  checkIndependentExamination(contractSource);
  checkAttribution(walk(ROOT));

  report();
}

function report() {
  process.stdout.write("\nPavvl adversarial review\n");
  for (const p of passes) process.stdout.write(`  ok    ${p}\n`);
  for (const a of advisories) process.stdout.write(`  warn  ${a}\n`);
  for (const f of failures) process.stdout.write(`  FAIL  ${f}\n`);
  process.stdout.write(
    `\n${passes.length} passed, ${advisories.length} advisory, ${failures.length} failed\n`,
  );
  process.exit(failures.length ? 1 : 0);
}

main();
